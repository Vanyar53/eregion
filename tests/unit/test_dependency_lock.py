"""M-3 (#183): the dependencies are locked, with hashes, and installed from the lock.

pyproject.toml declares ranges (`>=`); without a lock each build of H0's image took the
newest release of everything — a minor LiteLLM release once broke every decision (19/10).
The lock is two files generated by uv (`make lock`): requirements/dev.txt (CI, `make
install`) and requirements/glorfindel.txt (the image), the second constrained by the first,
so the image runs the versions CI tested. pip installs them in hash-checking mode.

Static checks only: nothing is resolved or downloaded here. That the lock installs on 3.11
and 3.12 is what CI does on every PR, from these files.
"""
import re
from pathlib import Path

import pytest

packaging = pytest.importorskip("packaging")
from packaging.markers import Marker  # noqa: E402
from packaging.requirements import Requirement  # noqa: E402
from packaging.utils import canonicalize_name  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DEV = ROOT / "requirements" / "dev.txt"
IMAGE = ROOT / "requirements" / "glorfindel.txt"
PINNED = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)\s*(?:;\s*([^\\]+?))?\s*\\?$")
HASH = re.compile(r"^\s+--hash=sha256:[0-9a-f]{64}\s*\\?$")


def _lock(path: Path) -> list[tuple[str, str, str, int]]:
    """(name, version, marker, number of hashes) per requirement; anything else fails."""
    out, current = [], None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if HASH.match(raw):
            assert current is not None, f"{path.name}: a hash before any requirement"
            current[3] += 1
            continue
        m = PINNED.match(raw)
        assert m, f"{path.name}: not a pinned requirement: {raw!r}"
        current = [canonicalize_name(m.group(1)), m.group(2), (m.group(3) or "").strip(), 0]
        out.append(current)
    return [tuple(x) for x in out]


def _for(lock, python: str) -> dict[str, str]:
    """name → version for Linux x86_64 on `python` (what CI and the image run)."""
    env = {"python_version": python, "python_full_version": f"{python}.0", "sys_platform": "linux",
           "platform_system": "Linux", "platform_machine": "x86_64", "os_name": "posix",
           "implementation_name": "cpython", "platform_python_implementation": "CPython",
           "extra": ""}
    out = {}
    for name, version, marker, _ in lock:
        if not marker or Marker(marker).evaluate(env):
            assert name not in out, f"{name} pinned twice for {python}"
            out[name] = version
    return out


def _declared(*extras: str) -> list[Requirement]:
    import tomllib
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    reqs = [Requirement(r) for r in project["dependencies"]]
    for extra in extras:
        for r in project["optional-dependencies"][extra]:
            req = Requirement(r)
            if canonicalize_name(req.name) == "eregion":       # dev = eregion[annatar,…] + tools
                reqs += _declared(*req.extras)
            else:
                reqs.append(req)
    build = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["build-system"]["requires"]
    return reqs + [Requirement(r) for r in build]


@pytest.mark.parametrize("path", [DEV, IMAGE], ids=["dev", "image"])
def test_every_requirement_is_pinned_with_its_hashes(path):
    lock = _lock(path)
    assert len(lock) > 50
    assert all(n_hashes >= 1 for *_, n_hashes in lock), [x for x in lock if x[3] == 0]
    header = path.read_text(encoding="utf-8").splitlines()[:2]
    assert "uv pip compile" in header[1]
    for flag in ("--universal", "--generate-hashes", "--python-version 3.11", "--exclude-newer"):
        assert flag in header[1], flag


@pytest.mark.parametrize("path, extras", [(IMAGE, ("glorfindel", "war-room")),
                                          (DEV, ("dev",))], ids=["image", "dev"])
@pytest.mark.parametrize("python", ["3.11", "3.12"])
def test_the_lock_satisfies_pyproject(path, extras, python):
    """A dependency added to pyproject.toml without `make lock` fails here, not in the image
    build (pip's hash-checking mode refuses a requirement missing from the lock)."""
    pinned = _for(_lock(path), python)
    for req in _declared(*extras):
        name = canonicalize_name(req.name)
        assert name in pinned, f"{req} is not in {path.name} — make lock"
        assert req.specifier.contains(pinned[name], prereleases=True), \
            f"{name}=={pinned[name]} in {path.name} does not satisfy {req} — make lock"


@pytest.mark.parametrize("python", ["3.11", "3.12"])
def test_the_image_runs_the_versions_ci_tested(python):
    dev, image = _for(_lock(DEV), python), _for(_lock(IMAGE), python)
    assert set(image) <= set(dev)
    assert {n: v for n, v in image.items() if dev[n] != v} == {}


def test_the_image_installs_from_the_lock_with_hashes_and_nothing_else():
    lines = [line.strip() for line in (ROOT / "glorfindel" / "Dockerfile").read_text(encoding="utf-8").splitlines()]
    installs = [line for line in lines if re.search(r"\bpip install\b", line)]
    assert installs, "no pip install in the image"
    lock_install = installs[0]
    assert "--require-hashes" in lock_install and "-r requirements/glorfindel.txt" in lock_install
    for line in installs[1:]:   # the project itself: no dependency resolved, no backend fetched
        assert "--no-deps" in line and "--no-build-isolation" in line, line
    assert "COPY requirements/glorfindel.txt" in "\n".join(lines)


def test_ci_and_make_install_use_the_dev_lock():
    for wf in ("ci.yml", "invariants.yml", "mutants.yml"):
        text = (ROOT / ".github" / "workflows" / wf).read_text(encoding="utf-8")
        installs = [line.strip() for line in text.splitlines() if "pip install" in line]
        assert installs, wf
        assert any("--require-hashes -r requirements/dev.txt" in i for i in installs), wf
        assert all("--require-hashes" in i or "--no-deps" in i for i in installs), (wf, installs)
    make = (ROOT / "Makefile").read_text(encoding="utf-8").split("\ninstall: venv\n")[1].split("\n\n")[0]
    assert "--require-hashes -r requirements/dev.txt" in make and "--no-deps" in make
