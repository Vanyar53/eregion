"""M-3 (#183): the dependencies are locked, with hashes, and installed from the lock.

pyproject.toml declares ranges (`>=`); without a lock each build of H0's image took the
newest release of everything — a minor LiteLLM release once broke every decision (19/10).
The lock is three files generated by uv (`make lock`): requirements/dev.txt (CI, `make
install`), requirements/glorfindel.txt (Glorfindel's image) and requirements/annatar.txt (the
injectors' image, Annatar and Gothmog, pushed to Orodruin — HY1), the last two constrained by
the first, so each image runs the versions CI tested. pip installs them in hash-checking mode.

Static checks only: nothing is resolved or downloaded here. That the lock installs on 3.11
and 3.12 is what CI does on every PR, from these files.
"""
import importlib.util
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

packaging = pytest.importorskip("packaging")
from packaging.markers import Marker  # noqa: E402
from packaging.requirements import Requirement  # noqa: E402
from packaging.utils import canonicalize_name  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DEV = ROOT / "requirements" / "dev.txt"
IMAGE = ROOT / "requirements" / "glorfindel.txt"
INJECTORS = ROOT / "requirements" / "annatar.txt"     # HY1: Annatar's image, Gothmog's too
PINNED = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)\s*(?:;\s*([^\\]+?))?\s*\\?$")
HASH = re.compile(r"^\s+--hash=sha256:[0-9a-f]{64}\s*\\?$")


def _lock(path: Path) -> list[tuple[str, str, str, int]]:
    """(name, version, marker, number of hashes) per requirement; anything else fails."""
    out, current = [], None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if HASH.match(raw):
            assert current is not None, f"{path.name}: a hash before any requirement"
            current[3] += 1
            continue
        m = PINNED.match(raw)
        assert m, f"{path.name}: not a pinned requirement: {raw!r}"
        current = [canonicalize_name(m.group(1)), m.group(2), (m.group(3) or "").strip(), 0]
        out.append(current)
    return [tuple(x) for x in out]


def _for(lock, python: str) -> dict[str, str]:
    """name → version for Linux x86_64 on `python` (what CI and the image run)."""
    env = {"python_version": python, "python_full_version": f"{python}.0", "sys_platform": "linux",
           "platform_system": "Linux", "platform_machine": "x86_64", "os_name": "posix",
           "implementation_name": "cpython", "platform_python_implementation": "CPython",
           "extra": ""}
    out = {}
    for name, version, marker, _ in lock:
        if not marker or Marker(marker).evaluate(env):
            assert name not in out, f"{name} pinned twice for {python}"
            out[name] = version
    return out


def _declared(*extras: str) -> list[Requirement]:
    import tomllib
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    reqs = [Requirement(r) for r in project["dependencies"]]
    for extra in extras:
        for r in project["optional-dependencies"][extra]:
            req = Requirement(r)
            if canonicalize_name(req.name) == "eregion":       # dev = eregion[annatar,…] + tools
                reqs += _declared(*req.extras)
            else:
                reqs.append(req)
    build = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["build-system"]["requires"]
    return reqs + [Requirement(r) for r in build]


@pytest.mark.parametrize("path", [DEV, IMAGE, INJECTORS], ids=["dev", "image", "injectors"])
def test_every_requirement_is_pinned_with_its_hashes(path):
    lock = _lock(path)
    assert len(lock) > 50
    assert all(n_hashes >= 1 for *_, n_hashes in lock), [x for x in lock if x[3] == 0]
    header = path.read_text(encoding="utf-8").splitlines()[:2]
    assert "uv pip compile" in header[1]
    for flag in ("--universal", "--generate-hashes", "--python-version 3.11", "--exclude-newer"):
        assert flag in header[1], flag


@pytest.mark.parametrize("path, extras", [(IMAGE, ("glorfindel", "war-room")),
                                          (INJECTORS, ("annatar",)),
                                          (DEV, ("dev",))], ids=["image", "injectors", "dev"])
@pytest.mark.parametrize("python", ["3.11", "3.12"])
def test_the_lock_satisfies_pyproject(path, extras, python):
    """A dependency added to pyproject.toml without `make lock` fails here, not in the image
    build (pip's hash-checking mode refuses a requirement missing from the lock)."""
    pinned = _for(_lock(path), python)
    for req in _declared(*extras):
        name = canonicalize_name(req.name)
        assert name in pinned, f"{req} is not in {path.name} — make lock"
        assert req.specifier.contains(pinned[name], prereleases=True), \
            f"{name}=={pinned[name]} in {path.name} does not satisfy {req} — make lock"


@pytest.mark.parametrize("lock", [IMAGE, INJECTORS], ids=["image", "injectors"])
@pytest.mark.parametrize("python", ["3.11", "3.12"])
def test_the_image_runs_the_versions_ci_tested(lock, python):
    dev, image = _for(_lock(DEV), python), _for(_lock(lock), python)
    assert set(image) <= set(dev)
    assert {n: v for n, v in image.items() if dev[n] != v} == {}


@pytest.mark.parametrize("dockerfile, lock", [("glorfindel/Dockerfile", "requirements/glorfindel.txt"),
                                              ("annatar/Dockerfile", "requirements/annatar.txt")],
                         ids=["glorfindel", "annatar"])
def test_the_image_installs_from_the_lock_with_hashes_and_nothing_else(dockerfile, lock):
    lines = [line.strip() for line in (ROOT / dockerfile).read_text(encoding="utf-8").splitlines()]
    installs = [line for line in lines if re.search(r"\bpip install\b", line)]
    assert installs, "no pip install in the image"
    lock_install = installs[0]
    assert "--require-hashes" in lock_install and f"-r {lock}" in lock_install
    for line in installs[1:]:   # the project itself: no dependency resolved, no backend fetched
        assert "--no-deps" in line and "--no-build-isolation" in line, line
    assert f"COPY {lock}" in "\n".join(lines)


@pytest.mark.parametrize("python", ["3.11", "3.12"])
def test_the_injectors_image_has_the_planner_s_llm_client(python):
    """HY1: `annatar campaign plan --llm` imports litellm; the injectors' image installed
    `.[annatar]`, whose extra did not declare it — the planner failed in the image only."""
    declared = {canonicalize_name(r.name) for r in _declared("annatar")}
    # litellm for the planner; jsonschema and requests, which the shared core imports, declared
    # rather than left to litellm and azure-core to bring.
    for name in ("litellm", "jsonschema", "requests"):
        assert name in _for(_lock(INJECTORS), python) and name in declared, name


def test_make_lock_writes_every_lock():
    """A lock that `make lock` no longer regenerates drifts from pyproject.toml unseen."""
    recipe = (ROOT / "Makefile").read_text(encoding="utf-8").split("\nlock:\n")[1].split("\n\n")[0]
    for lock in (DEV, IMAGE, INJECTORS):
        assert f"-o requirements/{lock.name}" in recipe, lock.name


def test_ci_and_make_install_use_the_dev_lock():
    for wf in ("ci.yml", "invariants.yml", "mutants.yml"):
        text = (ROOT / ".github" / "workflows" / wf).read_text(encoding="utf-8")
        installs = [line.strip() for line in text.splitlines() if "pip install" in line]
        assert installs, wf
        assert any("--require-hashes -r requirements/dev.txt" in i for i in installs), wf
        assert all("--require-hashes" in i or "--no-deps" in i for i in installs), (wf, installs)
    make = (ROOT / "Makefile").read_text(encoding="utf-8").split("\ninstall: venv\n")[1].split("\n\n")[0]
    assert "--require-hashes -r requirements/dev.txt" in make and "--no-deps" in make


# ── DEP2 (#590): one package raised alone, and kept there by the next make lock ──────────────
_spec = importlib.util.spec_from_file_location("lock_flags", ROOT / "scripts" / "lock_flags.py")
lock_flags = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lock_flags)
needs_make = pytest.mark.skipif(shutil.which("make") is None, reason="make not installed")
LOCKS = ("dev.txt", "glorfindel.txt", "annatar.txt", "audit.txt")


def _a_lock(path: Path, *pins: str, exceptions: str = "") -> Path:
    header = ("# This file was autogenerated by uv via the following command:\n"
              f"#    uv pip compile pyproject.toml --universal --exclude-newer 2026-10-26T00:00:00Z{exceptions} "
              f"-o {path.name}\n")
    path.write_text(header + "".join(f"{p} \\\n    --hash=sha256:{'0' * 64}\n" for p in pins), encoding="utf-8")
    return path


def test_upgrade_package_raises_it_only_in_the_locks_that_pin_it(tmp_path):
    held = _a_lock(tmp_path / "dev.txt", "oauthlib==4.0.0", "requests-oauthlib==2.0.0")
    other = _a_lock(tmp_path / "annatar.txt", "requests==2.33.0")
    assert lock_flags.flags(held, "2026-10-26", ["oauthlib"], "2026-11-05") == [
        "--upgrade-package", "oauthlib", "--exclude-newer-package", "oauthlib=2026-11-05T00:00:00Z"]
    # The others get nothing: uv writes them again byte for byte (their header too).
    assert lock_flags.flags(other, "2026-10-26", ["oauthlib"], "2026-11-05") == []
    # Already reachable at LOCK_DATE: raised, no date of its own.
    assert lock_flags.flags(held, "2026-11-05", ["oauthlib"], "2026-11-05") == ["--upgrade-package", "oauthlib"]
    # Named as pip would take it: the lock's own spelling.
    assert lock_flags.flags(held, "2026-10-26", lock_flags._names("Requests_OAuthlib"), "2026-11-05")[:2] == [
        "--upgrade-package", "requests-oauthlib"]


def test_the_date_a_lock_admits_a_package_at_is_passed_again_while_it_postdates_lock_date(tmp_path):
    """uv writes --exclude-newer-package into the header, never --upgrade-package: without it, the next
    make lock at the same LOCK_DATE took oauthlib back to 4.0.0 (measured, uv 0.13.6)."""
    lock = _a_lock(tmp_path / "dev.txt", "oauthlib==4.0.1",
                   exceptions=" --exclude-newer-package oauthlib=2026-11-05T00:00:00Z")
    assert lock_flags.exceptions(lock) == {"oauthlib": "2026-11-05"}
    assert lock_flags.flags(lock, "2026-10-26") == ["--exclude-newer-package", "oauthlib=2026-11-05T00:00:00Z"]
    # LOCK_DATE has caught up: the exception would cap oauthlib below it — dropped.
    assert lock_flags.flags(lock, "2026-11-05") == []
    assert lock_flags.flags(lock, "2027-01-01") == []
    # A lock not written yet has no exception.
    assert lock_flags.flags(tmp_path / "new.txt", "2026-10-26", ["oauthlib"], "2026-11-05") == []


def test_a_header_it_cannot_read_is_refused_never_taken_for_one_without_exceptions(tmp_path):
    """uv changes the form of its header: read as `{}`, the next make lock would take oauthlib back
    down without a word."""
    lock = tmp_path / "dev.txt"
    lock.write_text("# autogenerated by some other tool\n# pip-compile --generate-hashes\noauthlib==4.0.1 \\\n",
                    encoding="utf-8")
    with pytest.raises(SystemExit, match="n'est pas celui d'uv"):
        lock_flags.exceptions(lock)
    _a_lock(lock, "oauthlib==4.0.1", exceptions=" --exclude-newer-package oauthlib=2026-11-05")
    with pytest.raises(SystemExit, match="ne se lit pas"):
        lock_flags.exceptions(lock)


def test_the_committed_locks_admit_oauthlib_and_nothing_else_unread():
    """The locks as committed: their exceptions said outright, each one read, each one passed again
    by a make lock at the lock's own LOCK_DATE."""
    req = ROOT / "requirements"
    assert lock_flags.exceptions(req / "dev.txt") == {"oauthlib": "2026-11-05"}
    assert lock_flags.exceptions(req / "glorfindel.txt") == {"oauthlib": "2026-11-05"}
    assert lock_flags.exceptions(req / "annatar.txt") == {} and lock_flags.exceptions(req / "audit.txt") == {}
    for name in LOCKS:
        lock = req / name
        header = lock.read_text(encoding="utf-8").splitlines()[1]
        assert header.count("--exclude-newer-package") == len(lock_flags.exceptions(lock)), name
        date = re.search(r"--exclude-newer (\d{4}-\d{2}-\d{2})T", header).group(1)
        expected = [x for n, d in sorted(lock_flags.exceptions(lock).items())
                    for x in ("--exclude-newer-package", f"{n}={d}T00:00:00Z")]
        assert lock_flags.flags(lock, date) == expected, name
        for n in lock_flags.exceptions(lock):
            assert n in lock_flags.pinned(lock), (name, n)


def test_what_the_operator_typed_is_checked_before_any_lock_is_read():
    env = {"EREGION_LOCK_DATE": "2026-10-26", "EREGION_UPGRADE_PACKAGE": "OAuthlib, requests_oauthlib",
           "EREGION_UPGRADE_DATE": "2026-11-05"}
    assert lock_flags.from_env(env) == ("2026-10-26", ["oauthlib", "requests-oauthlib"], "2026-11-05")
    lock_date, upgrade, upgrade_date = lock_flags.from_env({})
    assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", lock_date) and upgrade == [] and upgrade_date == lock_date
    for key, bad in (("EREGION_UPGRADE_PACKAGE", "`touch x`"), ("EREGION_UPGRADE_PACKAGE", "a;b"),
                     ("EREGION_LOCK_DATE", "$(touch x)"), ("EREGION_UPGRADE_DATE", "26-10-2026")):
        with pytest.raises(SystemExit, match="invalide"):
            lock_flags.from_env({**env, key: bad})


def _repo_copy(tmp_path: Path) -> Path:
    """What make lock reads, copied: the Makefile, its scripts, the locks."""
    copy = tmp_path / "repo"
    for rel in ("Makefile", "scripts/lock_flags.py", "scripts/pip_audit_issues.py"):
        (copy / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, copy / rel)
    shutil.copytree(ROOT / "requirements", copy / "requirements")
    return copy


def _make_lock(tmp_path: Path, *extra: str, root: Path = ROOT):
    """make lock with a fake uv (it logs its arguments, writes nothing) on the locks of `root` (read
    only); the audit after it fails without a network (pip-audit is `false`), as make lock allows."""
    tmp_path.mkdir(parents=True, exist_ok=True)
    log, uv = tmp_path / "uv.log", tmp_path / "uv"
    uv.write_text(f'#!/bin/sh\necho "$*" >> "{log}"\n')
    uv.chmod(0o755)
    env = {k: v for k, v in os.environ.items()
           if k not in ("UPGRADE", "UPGRADE_PACKAGE", "UPGRADE_DATE", "LOCK_DATE", "MAKEFLAGS")
           and not k.startswith("EREGION_")}
    res = subprocess.run(["make", "-s", "--no-print-directory", "-C", str(root), "lock", f"UV={uv}",
                          f"PIP_AUDIT={shutil.which('false')}", *extra],
                         env=env, capture_output=True, text=True, timeout=120)
    calls = log.read_text().splitlines() if log.exists() else []
    return res, {c.rsplit("-o requirements/", 1)[1]: c for c in calls}


@needs_make
def test_make_lock_upgrade_package_moves_that_package_alone(tmp_path):
    before = {n: (ROOT / "requirements" / n).read_bytes() for n in LOCKS}
    res, calls = _make_lock(tmp_path, "UPGRADE_PACKAGE=oauthlib", "LOCK_DATE=2026-10-26", "UPGRADE_DATE=2026-11-05")
    assert res.returncode == 0, res.stdout + res.stderr
    assert sorted(calls) == sorted(LOCKS)
    for name in ("dev.txt", "glorfindel.txt"):                   # the two that pin oauthlib
        assert "--generate-hashes --exclude-newer 2026-10-26T00:00:00Z --upgrade-package oauthlib " \
               "--exclude-newer-package oauthlib=2026-11-05T00:00:00Z -o" in calls[name], calls[name]
    for name in ("annatar.txt", "audit.txt"):                    # untouched: their command as before
        assert "--generate-hashes --exclude-newer 2026-10-26T00:00:00Z -o" in calls[name] \
            and "package" not in calls[name]
    assert {n: (ROOT / "requirements" / n).read_bytes() for n in LOCKS} == before


@needs_make
def test_make_lock_keeps_the_raised_package_and_refuses_an_unknown_one(tmp_path):
    res, calls = _make_lock(tmp_path / "plain", "LOCK_DATE=2026-10-26", "UPGRADE=1")
    assert res.returncode == 0, res.stdout + res.stderr
    for name in LOCKS:
        held = lock_flags.exceptions(ROOT / "requirements" / name)
        assert all(f"--exclude-newer-package {n}={d}T00:00:00Z" in calls[name] for n, d in held.items()), calls[name]
        assert calls[name].endswith(" --upgrade -o requirements/" + name), calls[name]
    # A misspelt package: refused before uv runs, rather than every lock rewritten for nothing.
    res, calls = _make_lock(tmp_path / "typo", "UPGRADE_PACKAGE=oauthlb", "LOCK_DATE=2026-10-26")
    assert res.returncode != 0 and calls == {}
    assert "oauthlb n'est dans aucun verrou" in res.stderr


@needs_make
@pytest.mark.parametrize("variable", ["UPGRADE_PACKAGE", "LOCK_DATE", "UPGRADE_DATE"])
@pytest.mark.parametrize("form", ["`touch {w}`", "$(shell touch {w})", "$$(touch {w})", "x;touch {w}"])
def test_what_the_operator_typed_is_never_run(tmp_path, variable, form):
    """Neither make nor the shell expands the three: lock_flags.py reads them from its environment
    ($(value …), unexport) and refuses them before uv; the witness file is never created."""
    witness = tmp_path / "witness"
    res, calls = _make_lock(tmp_path, f"{variable}={form.format(w=witness)}")
    assert not witness.exists(), res.stdout + res.stderr
    assert res.returncode != 0 and calls == {}, calls
    assert "invalide" in res.stderr


@needs_make
@pytest.mark.parametrize("unreadable", LOCKS)
def test_make_lock_stops_at_the_lock_whose_flags_cannot_be_read(tmp_path, unreadable):
    """Each lock's flags read before its own uv: one header lock_flags.py cannot read stops make lock
    there — that lock never written without the exceptions it would have passed."""
    copy = _repo_copy(tmp_path)
    lock = copy / "requirements" / unreadable
    lines = lock.read_text(encoding="utf-8").splitlines(keepends=True)
    lock.write_text(lines[0] + "#    pip-compile --generate-hashes\n" + "".join(lines[2:]), encoding="utf-8")
    res, calls = _make_lock(tmp_path / "run", "LOCK_DATE=2026-10-26", root=copy)
    assert res.returncode != 0
    assert list(calls) == list(LOCKS[:LOCKS.index(unreadable)]), calls
    assert "n'est pas celui d'uv" in res.stderr
